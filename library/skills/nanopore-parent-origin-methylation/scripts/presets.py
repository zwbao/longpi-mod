def _cpg_key(text: str) -> str:
    return str(text).strip().lower().replace(":", "_").replace("-", "_")


def clock_age(values: dict[str, float]) -> tuple[float, int] | None:
    used: dict[str, float] = {}
    for raw, value in values.items():
        key = _cpg_key(raw)
        if key in CLOCK and key not in used:
            used[key] = CLOCK[key] * value
    if not used:
        return None
    return CLOCK_INTERCEPT + sum(used.values()), len(used)

