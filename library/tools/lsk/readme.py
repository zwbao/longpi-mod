"""Parse the README skill list, and regenerate it from skill.json.

The list between the markers is generated; everything outside them is
hand-written and kept. Old versions of dsh-plugin-longpi parse the bullet
format below, so keep it: - `skills/<name>/` — blurb
"""

from __future__ import annotations

import re
from typing import Any, Dict, List

BEGIN = "<!-- skills:begin (generated by python3 -m tools.lsk readme; edit skill.json instead) -->"
END = "<!-- skills:end -->"
BULLET = re.compile(r"^- `skills/([a-z0-9-]+)/`\s+[—-]\s+(.+?)\s*$")
HEADING = re.compile(r"^##\s+(.+?)\s*$")
CROSS_REF = re.compile(r"^见「")
DOMAIN_ORDER = [
    "临床年龄与可穿戴", "甲基化", "蛋白、代谢与器官年龄", "影像", "免疫与炎症", "脑、认知与痴呆", "衰弱与死亡风险",
    "线粒体", "营养感应", "老年保护", "自噬", "细胞衰老", "骨骼肌", "卵巢与生殖", "皮肤", "昼夜节律",
    "基质、软骨与纤维化", "再生", "长寿基因", "比较生物学", "端粒",
]
TOOLS_HEADING = "工具与证据库"


def plain(text: str) -> str:
    """Drop Markdown links and code ticks from a blurb."""
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    return text.replace("`", "").strip()


def parse_readme(text: str) -> Dict[str, Dict[str, Any]]:
    """name -> {"domains": [...], "blurb": str}, in README order."""
    found: Dict[str, Dict[str, Any]] = {}
    domain = "未归类"
    for line in text.splitlines():
        heading = HEADING.match(line)
        if heading:
            domain = heading.group(1).strip()
            continue
        bullet = BULLET.match(line)
        if not bullet:
            continue
        name, blurb = bullet.group(1), bullet.group(2).strip()
        entry = found.setdefault(name, {"domains": [], "blurb": ""})
        if domain not in entry["domains"]:
            entry["domains"].append(domain)
        if not CROSS_REF.match(blurb) and not entry["blurb"]:
            entry["blurb"] = plain(blurb)
    return found


def _order(domains: List[str]) -> List[str]:
    known = [item for item in DOMAIN_ORDER if item in domains]
    return known + sorted(item for item in domains if item not in DOMAIN_ORDER and item != TOOLS_HEADING)


def render_list(manifests: Dict[str, Dict[str, Any]]) -> str:
    tools = sorted(name for name, data in manifests.items() if data["tier"] == "tool")
    personal = {name: data for name, data in manifests.items() if data["tier"] in {"A", "B"}}
    indexed = {name: data for name, data in manifests.items() if data["tier"] == "C"}
    lines: List[str] = [BEGIN, "", f"## {TOOLS_HEADING}", "",
                        "这些目录包装已发布的程序、数据库或本仓库的证据库，不是把一篇论文重算成一个人的读出。", ""]
    for name in tools:
        lines.append(f"- `skills/{name}/` — {manifests[name]['blurb_zh']}")
    domains = _order(sorted({domain for data in personal.values() for domain in data["domains"]}))
    for domain in domains:
        lines += ["", f"## {domain}", ""]
        for name in sorted(personal):
            data = personal[name]
            if domain not in data["domains"]:
                continue
            primary = data["domains"][0]
            if domain == primary:
                suffix = "（名单类）" if data["tier"] == "B" else ""
                lines.append(f"- `skills/{name}/` — {data['blurb_zh']}{suffix}")
            else:
                lines.append(f"- `skills/{name}/` — 见「{primary}」。")
    lines += ["", "## 只收录，不参与个人调度", "",
              "下面这些是动物、细胞实验，或者输入只能是队列统计量的方法。它们留在仓库里供检索和科普，个人问题不会调度到它们，除非问题点名了对应的模式生物。"]
    for domain in _order(sorted({data["domains"][0] for data in indexed.values()})):
        lines += ["", f"### {domain}", ""]
        for name in sorted(indexed):
            if indexed[name]["domains"][0] == domain:
                lines.append(f"- `skills/{name}/` — {indexed[name]['blurb_zh']}")
    lines += ["", END]
    return "\n".join(lines) + "\n"


def splice(readme: str, generated: str) -> str:
    """Replace the generated region; if no markers yet, replace from the tools heading on."""
    if BEGIN in readme and END in readme:
        head = readme[: readme.index(BEGIN)]
        tail = readme[readme.index(END) + len(END):]
        return head + generated.rstrip("\n") + tail if tail.strip() else head + generated
    marker = f"## {TOOLS_HEADING}"
    head = readme[: readme.index(marker)] if marker in readme else readme.rstrip("\n") + "\n\n"
    return head + generated
